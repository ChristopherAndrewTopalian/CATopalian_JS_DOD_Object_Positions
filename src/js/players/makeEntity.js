// makeEntity.js

function makeEntity(whichObj)
{
    return {
        id: whichObj.id,
        name: whichObj.name,
        color: whichObj.color,
        x: whichObj.x,
        y: whichObj.y,
        width: whichObj.width,
        height: whichObj.height,
        vx: 5, // Default speed for all players
        vy: 5,
        angle: 0,
    };
}

